export type SentenceToken = {
  surface: string;
  reading: string;
  ruby?: boolean;
};

export type SentenceRegister = "polite" | "casual";

export type PracticeSentence = {
  id: number;
  family: string;
  category: string;
  register: SentenceRegister;
  tokens: SentenceToken[];
  reading: string;
};

type Phrase = SentenceToken[];

type RegisterPhrase = {
  polite: Phrase;
  casual: Phrase;
};

type SentenceFamily = {
  id: string;
  category: string;
  contexts: Phrase[];
  connector: Phrase;
  predicates: RegisterPhrase[];
};

const punctuation = new Set(["、", "。", "！", "？", "「", "」"]);

const plain = (surface: string, reading = surface): SentenceToken => ({
  surface,
  reading,
});

const ruby = (surface: string, reading: string): SentenceToken => ({
  surface,
  reading,
  ruby: true,
});

const katakanaToHiragana = (value: string) =>
  Array.from(value, (character) => {
    const code = character.charCodeAt(0);
    return code >= 0x30a1 && code <= 0x30f6
      ? String.fromCharCode(code - 0x60)
      : character;
  }).join("");

/**
 * Sentence data uses {surface|reading} for kanji. Katakana outside braces is
 * displayed as-is while its reading is converted to hiragana automatically.
 */
const phrase = (source: string): Phrase => {
  const tokens: Phrase = [];
  const pattern = /\{([^|{}]+)\|([^{}]+)\}/g;
  let cursor = 0;

  const pushPlain = (value: string) => {
    for (const part of value.split(/([、。！？「」])/).filter(Boolean)) {
      tokens.push(
        punctuation.has(part)
          ? plain(part, "")
          : plain(part, katakanaToHiragana(part)),
      );
    }
  };

  for (const match of source.matchAll(pattern)) {
    const index = match.index ?? 0;
    if (index > cursor) pushPlain(source.slice(cursor, index));
    tokens.push(ruby(match[1], match[2]));
    cursor = index + match[0].length;
  }

  if (cursor < source.length) pushPlain(source.slice(cursor));
  return tokens;
};

const phraseList = (...values: string[]) => values.map(phrase);

const registerPhrase = (polite: string, casual: string): RegisterPhrase => ({
  polite: phrase(polite),
  casual: phrase(casual),
});

const registerList = (...values: Array<[string, string]>) =>
  values.map(([polite, casual]) => registerPhrase(polite, casual));

