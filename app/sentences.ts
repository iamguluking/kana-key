const casualTones = phraseList("", "よ", "ね", "んだ", "かな");
const fullStop = plain("。", "");

export const sentenceBank: PracticeSentence[] = [];

for (const [familyIndex, family] of families.entries()) {
  for (const [contextIndex, context] of family.contexts.entries()) {
    for (const [predicateIndex, predicate] of family.predicates.entries()) {
      for (const register of ["polite", "casual"] as const) {
        const tone =
          register === "casual"
            ? casualTones[
                (familyIndex + contextIndex * 3 + predicateIndex) %
                  casualTones.length
              ]
            : [];
        const tokens = [
          ...context,
          ...family.connector,
          ...predicate[register],
          ...tone,
          fullStop,
        ];

        sentenceBank.push({
          id: sentenceBank.length + 1,
          family: family.id,
          category: family.category,
          register,
          tokens,
          reading: tokens.map((token) => token.reading).join(""),
        });
      }
    }
  }
}

const shuffle = <T>(values: T[], random: () => number) => {
  for (let index = values.length - 1; index > 0; index -= 1) {
    const other = Math.floor(random() * (index + 1));
    [values[index], values[other]] = [values[other], values[index]];
  }
  return values;
};

/**
 * Creates one no-replacement practice cycle. Every round visits each of the
 * 50 sentence families once, so adjacent prompts never share a sentence frame.
 */
export function createPracticeDeck(random: () => number = Math.random) {
  const buckets = new Map<string, number[]>();

  sentenceBank.forEach((sentence, index) => {
    const bucket = buckets.get(sentence.family) ?? [];
    bucket.push(index);
    buckets.set(sentence.family, bucket);
  });

  for (const bucket of buckets.values()) shuffle(bucket, random);

  const deck: number[] = [];
  let previousFamily: string | null = null;

  while ([...buckets.values()].some((bucket) => bucket.length > 0)) {
    const availableFamilies = shuffle(
      [...buckets.entries()]
        .filter(([, bucket]) => bucket.length > 0)
        .map(([family]) => family),
      random,
    );

    if (
      availableFamilies.length > 1 &&
      availableFamilies[0] === previousFamily
    ) {
      [availableFamilies[0], availableFamilies[1]] = [
        availableFamilies[1],
        availableFamilies[0],
      ];
    }

    for (const family of availableFamilies) {
      const index = buckets.get(family)?.pop();
      if (index !== undefined) deck.push(index);
      previousFamily = family;
    }
  }

  return deck;
}
